"""Prove caching is active and private WooCommerce flows remain excluded."""
import json,requests,pathlib,os,time
from bs4 import BeautifulSoup
base='http://127.0.0.1:8089';f=json.load(open('/tmp/crmp-optimization-fixture.json'))
def check(label,ok):
    assert ok,label
    print('PASS OPTIMIZATION '+label,flush=True)
probe=requests.get(base+'/?crmp_object_cache_probe=1',timeout=30).json()
check('Redis marker survives CLI-to-HTTP process boundary',probe['persistent'] and probe['marker']=='alive')
first=requests.get(f['public_url'],timeout=30)
first_marker=BeautifulSoup(first.text,'html.parser').select_one('[data-crmp-cache-render]')
# The response body may arrive before PHP shutdown finishes writing the cache.
# Wait for this exact render on disk, rather than racing the writer with GET #2.
cached_files=[]
deadline=time.monotonic()+10
while time.monotonic()<deadline:
    cached_files=[]
    for file in (pathlib.Path(os.environ['CRMP_WP_PATH'])/'wp-content/cache').rglob('*.html'):
        try:
            disk_marker=BeautifulSoup(file.read_bytes(),'html.parser').select_one('[data-crmp-cache-render]')
        except OSError:
            continue
        if first_marker and disk_marker and disk_marker.get('data-crmp-cache-render')==first_marker.get('data-crmp-cache-render'):
            cached_files.append(str(file))
    if cached_files:break
    time.sleep(0.1)
second=requests.get(f['public_url'],timeout=30)
second_marker=BeautifulSoup(second.text,'html.parser').select_one('[data-crmp-cache-render]')
if not cached_files or not first_marker or not second_marker or first_marker.get('data-crmp-cache-render')!=second_marker.get('data-crmp-cache-render'):
    print('::notice title=Cache diagnostic::'+json.dumps({'first_status':first.status_code,'second_status':second.status_code,'url':second.url,'cache_control':second.headers.get('Cache-Control'),'cache_files':cached_files,'runtime':second.headers.get('X-CRMP-Cache-Diagnostic'),'render_markers_present':bool(first_marker and second_marker),'cookies':list(second.cookies.keys())}),flush=True)
if not cached_files or not first_marker or not second_marker or first_marker.get('data-crmp-cache-render')!=second_marker.get('data-crmp-cache-render'):
    debug=pathlib.Path(os.environ['CRMP_WP_PATH'])/'wp-content/cache/crmp-public-cache-debug.php'
    if debug.exists():
        lines=[line for line in debug.read_text(errors='replace').splitlines() if 'cookie' not in line.lower()][-80:]
        for line in lines:print('::notice title=Public cache skip reason::'+line.replace('%','%25'),flush=True)
check('public page really is cached',bool(cached_files) and first_marker is not None and second_marker is not None and first_marker['data-crmp-cache-render']==second_marker['data-crmp-cache-render'])
print('::notice title=Cache transport::'+json.dumps({'mode':f['mode'],'public_content_encoding':second.headers.get('Content-Encoding','identity'),'cache_served_header':second.headers.get('X-WP-Super-Cache'), 'same_render':first_marker['data-crmp-cache-render']==second_marker['data-crmp-cache-render']}),flush=True)
if os.environ.get('CRMP_CACHE_ONLY')=='1':
    print('RESULT: ONLY THE PREVIOUSLY FAILING PUBLIC CACHE CHECK PASSED',flush=True)
    raise SystemExit(0)
server=json.load(open('/tmp/crmp-server-fixture.json'));guest=requests.Session();guest.post(base+'/?wc-ajax=add_to_cart',data={'product_id':server['product'],'quantity':1},timeout=30)
r=guest.get(base+'/?page_id='+str(server['checkout_page']),timeout=60);doc=BeautifulSoup(r.text,'html.parser')
check('checkout remains private and has fresh server form',doc.select_one('[name=woocommerce-process-checkout-nonce]') is not None and 'Cached page generated by WP-Super-Cache' not in r.text)
check('actual optimized JS URL present','autoptimize_' in r.text and any('autoptimize_' in s.get('src','') for s in doc.select('script[src]')))
if f['mode']=='inline':check('inline CSS contains dynamic proof styles',any('crmp-upload-feedback' in s.text for s in doc.select('style')))
else:check('combined stylesheet URL present',any('autoptimize_' in s.get('href','') for s in doc.select('link[rel=stylesheet]')))
print('RESULT: ACTIVE PAGE/OBJECT CACHE AND OPTIMIZER CHECKS PASSED',flush=True)
